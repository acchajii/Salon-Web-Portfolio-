
import os
from datetime import datetime
from flask import Flask, render_template, request, redirect, url_for, flash
from dotenv import load_dotenv
import psycopg2
from psycopg2.extras import RealDictCursor

load_dotenv()

app = Flask(__name__)
app.secret_key = os.getenv("SECRET_KEY", "change-this-secret")

DATABASE_URL = os.getenv("DATABASE_URL")


def get_connection():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL is not configured")

    return psycopg2.connect(
        DATABASE_URL,
        sslmode="require",
        connect_timeout=15
    )


def init_db():
    conn = get_connection()
    cur = conn.cursor()

    cur.execute("""
        CREATE TABLE IF NOT EXISTS appointments (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            customer_name VARCHAR(120) NOT NULL,
            phone VARCHAR(30) NOT NULL,
            service VARCHAR(100) NOT NULL,
            preferred_date DATE NOT NULL,
            message TEXT,
            status VARCHAR(30) DEFAULT 'Pending',
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
        )
    """)

    conn.commit()
    cur.close()
    conn.close()


@app.route("/")
def home():
    return render_template("index.html")


@app.route("/book", methods=["POST"])
def book():
    name = request.form.get("name", "").strip()
    phone = request.form.get("phone", "").strip()
    service = request.form.get("service", "").strip()
    date = request.form.get("date", "").strip()
    message = request.form.get("message", "").strip()

    if not all([name, phone, service, date]):
        flash("Please complete all required fields.", "error")
        return redirect(url_for("home") + "#booking")

    try:
        datetime.strptime(date, "%Y-%m-%d")

        conn = get_connection()
        cur = conn.cursor()

        cur.execute("""
            INSERT INTO appointments
            (customer_name, phone, service, preferred_date, message)
            VALUES (%s, %s, %s, %s, %s)
        """, (name, phone, service, date, message))

        conn.commit()
        cur.close()
        conn.close()

        flash(
            "Your appointment request has been received. Our team will contact you to confirm.",
            "success"
        )

    except Exception:
        app.logger.exception("Appointment submission failed")
        flash(
            "We couldn't submit your request right now. Please try again or contact the salon.",
            "error"
        )

    return redirect(url_for("home") + "#booking")


@app.route("/health")
def health():
    return {"status": "healthy"}, 200


@app.route("/admin")
def admin():
    try:
        conn = get_connection()
        cur = conn.cursor(cursor_factory=RealDictCursor)

        cur.execute("""
            SELECT * FROM appointments
            ORDER BY created_at DESC
        """)

        appointments = cur.fetchall()
        cur.close()
        conn.close()

    except Exception:
        app.logger.exception("Admin database request failed")
        appointments = []
        flash("Database connection failed.", "error")

    return render_template("admin.html", appointments=appointments)


@app.route("/admin/status/<int:appointment_id>", methods=["POST"])
def update_status(appointment_id):
    status = request.form.get("status", "Pending")

    if status not in ["Pending", "Confirmed", "Completed", "Cancelled"]:
        flash("Invalid status.", "error")
        return redirect(url_for("admin"))

    try:
        conn = get_connection()
        cur = conn.cursor()

        cur.execute("""
            UPDATE appointments
            SET status = %s
            WHERE id = %s
        """, (status, appointment_id))

        conn.commit()
        cur.close()
        conn.close()

        flash("Appointment status updated.", "success")

    except Exception:
        app.logger.exception("Status update failed")
        flash("Could not update appointment status.", "error")

    return redirect(url_for("admin"))


with app.app_context():
    init_db()


if __name__ == "__main__":
    app.run(
        host="0.0.0.0",
        port=int(os.getenv("PORT", "5000")),
        debug=False
    )

        
